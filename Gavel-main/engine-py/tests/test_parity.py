"""Parity: the Python engine must agree with the TypeScript engine.

`fixtures/parity.json` is generated by the TypeScript engine
(`src/lib/engine/evaluate.ts`). If these tests pass, a decision is identical
whichever service produced it, which is the whole point of a deterministic
engine.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from app.engine import analyze
from app.schemas import Txn

FIXTURE = Path(__file__).parent / "fixtures" / "parity.json"
CASES = json.loads(FIXTURE.read_text())["cases"]


@pytest.mark.parametrize("case", CASES, ids=[c["id"] for c in CASES])
def test_python_matches_typescript(case: dict) -> None:
    txns = [Txn(**t) for t in case["transactions"]]
    result = analyze(txns, f"{case['months']} months")
    expected = case["expected"]

    assert result.decision == expected["decision"]
    assert result.risk_score == expected["risk_score"]
    assert result.credit_limit == expected["credit_limit"]
    assert result.policy_id == expected["policy_id"]
    assert result.confidence == pytest.approx(expected["confidence"], abs=0.01)

    # Signals must match to the rupee / basis point.
    py_signals = result.signals.model_dump()
    for key, value in expected["signals"].items():
        if isinstance(value, float):
            assert py_signals[key] == pytest.approx(value, abs=0.001), key
        else:
            assert py_signals[key] == value, key

    # Same rules, same verdicts, same order.
    assert [(r.id, r.result, r.skipped) for r in result.rules_fired] == [
        (r["id"], r["result"], r["skipped"]) for r in expected["rules_fired"]
    ]
